#!/usr/bin/env python3
"""Write plain T-SQL SSMS copies: no ':' directives, no $(vars).

wte_NtcaDatabase and ntca_app / NtcaAppDev2026x are hardcoded
(DEV ONLY — change for production).
"""
from __future__ import annotations

import re
from pathlib import Path

DB = Path(__file__).resolve().parents[1]
SSMS = DB / "ssms"
DATABASE = "wte_NtcaDatabase"
PASSWORD = "NtcaAppDev2026x"

FILES = [
    "00_create_database.sql",
    "01_schema.sql",
    "02_seed.sql",
    "seed/SEED_00_static_pages.sql",
    "seed/SEED_10_shops.sql",
    "seed/SEED_15_ctca_members.sql",
    "seed/SEED_16_top100_shops.sql",
    "seed/SEED_20_events.sql",
    "seed/SEED_30_blog_bloggers.sql",
    "seed/SEED_40_about_bios.sql",
    "seed/SEED_50_gallery_media.sql",
    "seed/SEED_60_manufacturers.sql",
    "seed/SEED_65_glossary_conditions.sql",
    "seed/SEED_70_industry_figures.sql",
    "03_app_login.sql",
]

SQLCMD_BANNER = (
    "/* SSMS: enable Query > SQLCMD Mode before running.\n"
    "   ':' directives (:on error, :setvar, :r) and $(vars) fail if SQLCMD Mode is off.\n"
    "   Plain T-SQL (no SQLCMD Mode): db/ssms/NTCA_FULL_INSTALL_SSMS.sql\n"
    "*/\n"
)

FULL_BANNER = f"""/* Plain T-SQL for SSMS — SQLCMD Mode is NOT required.
   Database: {DATABASE} (hardcoded). Login: ntca_app.
   DEV ONLY password {PASSWORD} — change for production.
   Generated by db/tools/generate_ssms.py — do not hand-edit.
*/

DECLARE @AppPassword nvarchar(128) = N'{PASSWORD}'; -- DEV ONLY; login below uses the same value
GO
"""

CREATE_DB = f"""/* ==== 00_create_database ==== */
IF DB_ID(N'{DATABASE}') IS NULL
    CREATE DATABASE [{DATABASE}];
GO
ALTER DATABASE [{DATABASE}] SET RECOVERY FULL;
IF NOT EXISTS (
    SELECT 1 FROM sys.databases
    WHERE name = N'{DATABASE}' AND is_read_committed_snapshot_on = 1)
    ALTER DATABASE [{DATABASE}] SET READ_COMMITTED_SNAPSHOT ON WITH ROLLBACK IMMEDIATE;
ALTER DATABASE [{DATABASE}] SET ALLOW_SNAPSHOT_ISOLATION ON;
ALTER DATABASE [{DATABASE}] SET AUTO_CREATE_STATISTICS ON;
ALTER DATABASE [{DATABASE}] SET AUTO_UPDATE_STATISTICS ON;
GO
PRINT '{DATABASE} options: RECOVERY FULL, READ_COMMITTED_SNAPSHOT ON';
GO
USE [{DATABASE}];
GO
"""

LOGIN = f"""/* ==== 03_app_login ==== */
USE [master];
GO
IF NOT EXISTS (SELECT 1 FROM sys.server_principals WHERE name = N'ntca_app')
    CREATE LOGIN [ntca_app] WITH PASSWORD = N'{PASSWORD}', CHECK_POLICY = ON, CHECK_EXPIRATION = OFF, DEFAULT_DATABASE = [{DATABASE}];
ELSE
    ALTER LOGIN [ntca_app] WITH PASSWORD = N'{PASSWORD}' UNLOCK, CHECK_POLICY = ON;
PRINT 'Login ntca_app ready (DEV ONLY password {PASSWORD} — change for production)';
GO
USE [{DATABASE}];
GO
IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = N'ntca_app')
    CREATE USER [ntca_app] FOR LOGIN [ntca_app];
GO
ALTER ROLE db_datareader ADD MEMBER [ntca_app];
ALTER ROLE db_datawriter ADD MEMBER [ntca_app];
GO
GRANT EXECUTE ON SCHEMA::core  TO [ntca_app];
GRANT EXECUTE ON SCHEMA::dir   TO [ntca_app];
GRANT EXECUTE ON SCHEMA::bill  TO [ntca_app];
GRANT EXECUTE ON SCHEMA::mkt   TO [ntca_app];
GRANT EXECUTE ON SCHEMA::feed  TO [ntca_app];
GRANT EXECUTE ON SCHEMA::ugc   TO [ntca_app];
GRANT EXECUTE ON SCHEMA::karma TO [ntca_app];
GRANT EXECUTE ON SCHEMA::crm   TO [ntca_app];
GRANT EXECUTE ON SCHEMA::cms   TO [ntca_app];
GRANT EXECUTE ON SCHEMA::seo   TO [ntca_app];
GRANT EXECUTE ON SCHEMA::analytics TO [ntca_app];
GO
PRINT 'Granted db_datareader, db_datawriter, EXECUTE on app schemas to ntca_app';
GO
"""

FILE_BANNER = f"""/* Plain T-SQL for SSMS — SQLCMD Mode is NOT required.
   Database: {DATABASE}. Generated by db/tools/generate_ssms.py.
*/
"""

SQLCMD_LINE = re.compile(
    r"^[ \t]*:(on error exit|r\s|setvar\s|!!|out\s|error\s|reset\s|list\s|quit\b)",
    re.I,
)
DEAD_VAR_CHECK = re.compile(
    r"IF LEN\(N'(?:wte_NtcaDatabase|ntca_app|__SKIP__|CHANGE_ME)'\).*?"
    r"(?:RAISERROR\([^)]+\);\s*(?:RETURN;)?\s*)+",
    re.S,
)


def strip_sqlcmd(sql: str) -> str:
    sql = re.sub(
        r"/\* SSMS: enable Query > SQLCMD Mode before running\..*?\*/\n*",
        "",
        sql,
        flags=re.S,
    )
    kept: list[str] = []
    for line in sql.splitlines(keepends=True):
        if SQLCMD_LINE.match(line):
            continue
        kept.append(line)
    return "".join(kept)


def subst(sql: str) -> str:
    sql = sql.replace("$(NtcaDatabase)", DATABASE)
    sql = sql.replace("$(NtcaAppLogin)", "ntca_app")
    sql = sql.replace("$(NtcaMigratorLogin)", "ntca_migrator")
    sql = sql.replace("N'$(NtcaAppPassword)'", f"N'{PASSWORD}'")
    sql = sql.replace("N'$(NtcaMigratorPassword)'", "N'__SKIP__'")
    sql = sql.replace("$(NtcaAppPassword)", PASSWORD)
    sql = sql.replace("$(NtcaMigratorPassword)", "__SKIP__")
    return sql


def leftover_sqlcmd(sql: str) -> list[str]:
    hits: list[str] = []
    for i, line in enumerate(sql.splitlines(), 1):
        if SQLCMD_LINE.match(line) or "$(Ntca" in line or re.search(r"\$\([A-Za-z]", line):
            hits.append(f"{i}:{line.strip()[:80]}")
    return hits


def transform_body(sql: str) -> str:
    text = subst(strip_sqlcmd(sql))
    text = DEAD_VAR_CHECK.sub("", text)
    return text


def ssms_name(rel: str) -> str:
    name = Path(rel).name
    return name[:-4] + "_SSMS.sql" if name.endswith(".sql") else name


def ensure_sqlcmd_banners() -> None:
    targets = [
        DB / "00_create_database.sql",
        DB / "01_schema.sql",
        DB / "02_seed.sql",
        DB / "03_app_login.sql",
        DB / "tools" / "validate.sql",
        *[DB / f for f in FILES if f.startswith("seed/")],
    ]
    for path in targets:
        text = path.read_text(encoding="utf-8")
        if text.startswith("/* SSMS: enable Query > SQLCMD Mode"):
            continue
        path.write_text(SQLCMD_BANNER + text, encoding="utf-8")


def main() -> int:
    ensure_sqlcmd_banners()
    SSMS.mkdir(parents=True, exist_ok=True)
    parts = [FULL_BANNER, CREATE_DB]
    for rel in FILES:
        if rel in ("00_create_database.sql", "03_app_login.sql"):
            continue
        src = transform_body((DB / rel).read_text(encoding="utf-8"))
        if not src.endswith("\n"):
            src += "\n"
        dest = SSMS / ssms_name(rel)
        dest.write_text(FILE_BANNER + src, encoding="utf-8")
        leftover = leftover_sqlcmd(FILE_BANNER + src)
        if leftover:
            raise SystemExit(f"SQLCMD leftovers in {dest}: {leftover[:5]}")
        concat = src
        if rel == "01_schema.sql":
            concat = re.sub(
                r"^USE \[wte_NtcaDatabase\];\s*\nGO\s*\n",
                "",
                src,
                count=1,
                flags=re.M,
            )
        parts.append(f"\n/* ==== {rel} ==== */\n")
        parts.append(concat)

    (SSMS / "00_create_database_SSMS.sql").write_text(FILE_BANNER + CREATE_DB, encoding="utf-8")
    (SSMS / "03_app_login_SSMS.sql").write_text(FILE_BANNER + LOGIN, encoding="utf-8")
    parts.append(LOGIN)
    full = "".join(parts)
    leftover = leftover_sqlcmd(full)
    if leftover:
        raise SystemExit(f"SQLCMD leftovers in full install: {leftover[:8]}")
    if ":on error" in full or ":setvar" in full:
        raise SystemExit("SQLCMD directives leaked into full install")
    (SSMS / "NTCA_FULL_INSTALL_SSMS.sql").write_text(full, encoding="utf-8")
    print("Wrote db/ssms/*.sql and db/ssms/NTCA_FULL_INSTALL_SSMS.sql")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
