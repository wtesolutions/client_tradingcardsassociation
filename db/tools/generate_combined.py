#!/usr/bin/env python3
"""Write db/run_all.sql (:r chain) and db/NTCA_FULL_INSTALL.sql (inlined)."""
from __future__ import annotations

from pathlib import Path

DB = Path(__file__).resolve().parents[1]
FILES = [
    "00_create_database.sql",
    "01_schema.sql",
    "02_seed.sql",
    "seed/SEED_00_static_pages.sql",
    "seed/SEED_10_shops.sql",
    "seed/SEED_15_ctca_members.sql",
    "seed/SEED_16_top100_shops.sql",
    "seed/SEED_20_events.sql",
    "seed/SEED_30_blog_bloggers.sql",
    "seed/SEED_40_about_bios.sql",
    "seed/SEED_50_gallery_media.sql",
    "seed/SEED_60_manufacturers.sql",
    "seed/SEED_65_glossary_conditions.sql",
    "seed/SEED_70_industry_figures.sql",
    "03_app_login.sql",
]


def main() -> int:
    missing = [f for f in FILES if not (DB / f).exists()]
    if missing:
        raise SystemExit(f"Missing: {missing}")

    run_all = [
        "/* One-shot sqlcmd apply. Requires SQLCMD mode (sqlcmd.exe or SSMS Query → SQLCMD Mode).\n",
        "   cd db\n",
        "   sqlcmd -S localhost,1433 -U sa -P \"...\" -C -I -i run_all.sql `\n",
        "     -v NtcaDatabase=NTCA -v NtcaAppLogin=ntca_app `\n",
        "     -v NtcaAppPassword=\"...\"\n",
        "   Optional: -v NtcaMigratorPassword=...\n",
        "   $(NtcaAppPassword) is required by 03_app_login.sql.\n",
        "*/\n",
        ":on error exit\n",
        "\n",
    ]
    for f in FILES:
        run_all.append(f":r {f}\n")
    (DB / "run_all.sql").write_text("".join(run_all), encoding="utf-8")

    parts = [
        "/* NTCA_FULL_INSTALL.sql — concatenated 00 → 01 → 02 → SEED_* → 03.\n",
        "   SSMS: Query → SQLCMD Mode, then:\n",
        "     :setvar NtcaDatabase NTCA\n",
        "     :setvar NtcaAppLogin ntca_app\n",
        "     :setvar NtcaAppPassword ***REPLACE***\n",
        "   Or sqlcmd -i NTCA_FULL_INSTALL.sql -v NtcaDatabase=NTCA -v NtcaAppPassword=...\n",
        "   Generated by db/tools/generate_combined.py — do not hand-edit.\n",
        "*/\n",
        ":on error exit\n",
        "\n",
    ]
    for f in FILES:
        parts.append(f"\n/* ==== {f} ==== */\n")
        parts.append((DB / f).read_text(encoding="utf-8"))
        if not parts[-1].endswith("\n"):
            parts.append("\n")
    (DB / "NTCA_FULL_INSTALL.sql").write_text("".join(parts), encoding="utf-8")
    print("Wrote db/run_all.sql and db/NTCA_FULL_INSTALL.sql")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
