#!/usr/bin/env python3
"""Write db/NTCA_FULL_INSTALL.sql (plain T-SQL, concatenated GO batches)."""
from __future__ import annotations

import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
from sql_order import FILES  # noqa: E402

DB = TOOLS.parent

BANNER = """/* Plain T-SQL for SSMS. SQLCMD Mode is not required.
   NTCA_FULL_INSTALL.sql — concatenated 00 → 01 → 04 → 05 → 06 → 02 → SEED_* → 03.
   Database: wte_NtcaDatabase. Login: ntca_app / NtcaAppDev2026x (DEV ONLY — change for production).
   Optional migrator: edit DECLARE @MigratorPassword in the 03_app_login section (default N'__SKIP__').
   Generated by db/tools/generate_combined.py — do not hand-edit.
   SET XACT_ABORT ON is set in each script; errors abort the batch.
*/
"""


def leftover_hits(sql: str) -> list[str]:
    hits: list[str] = []
    for i, line in enumerate(sql.splitlines(), 1):
        stripped = line.lstrip()
        if stripped.startswith(":"):
            hits.append(f"{i}: colon-directive {line.strip()[:80]}")
        if "$(" in line:
            hits.append(f"{i}: dollar-paren {line.strip()[:80]}")
    return hits


def main() -> int:
    missing = [f for f in FILES if not (DB / f).exists()]
    if missing:
        raise SystemExit(f"Missing: {missing}")

    parts = [BANNER]
    for f in FILES:
        text = (DB / f).read_text(encoding="utf-8")
        if not text.endswith("\n"):
            text += "\n"
        parts.append(f"\n/* ==== {f} ==== */\n")
        parts.append(text)
        if not text.rstrip().endswith("GO"):
            parts.append("GO\n")

    full = "".join(parts)
    leftover = leftover_hits(full)
    if leftover:
        raise SystemExit(f"SQLCMD leftovers in NTCA_FULL_INSTALL.sql: {leftover[:8]}")
    (DB / "NTCA_FULL_INSTALL.sql").write_text(full, encoding="utf-8")
    print("Wrote db/NTCA_FULL_INSTALL.sql")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
